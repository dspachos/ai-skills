// Regenerates docs/skills-data.js from skills/ and scripts/site-manifest.json.
// Run it after you add or change a skill: node scripts/build-site-data.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, "skills");
const manifest = JSON.parse(readFileSync(join(root, "scripts/site-manifest.json"), "utf8"));

function parseFrontmatter(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!match) return { name: "", description: "", body: text };
  const fields = {};
  for (const line of match[1].split("\n")) {
    const sep = line.indexOf(":");
    if (sep > 0) fields[line.slice(0, sep).trim()] = line.slice(sep + 1).trim();
  }
  return {
    name: fields.name ?? "",
    description: fields.description ?? "",
    body: text.slice(match[0].length),
  };
}

const skills = [];
for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = join(skillsDir, entry.name, "SKILL.md");
  try {
    const { name, description, body } = parseFrontmatter(readFileSync(file, "utf8"));
    skills.push({
      slug: entry.name,
      name: name || entry.name,
      description,
      doc: body.trim(),
      ...(manifest.skills[entry.name] ?? {}),
    });
  } catch {
    console.error(`warn: no SKILL.md in skills/${entry.name}, skipped`);
  }
}

const byGroup = new Map(manifest.groups.map((g) => [g.name, []]));
const other = [];
for (const skill of skills) {
  const bucket = byGroup.get(skill.group);
  if (bucket) bucket.push(skill);
  else other.push(skill);
}
if (other.length > 0) {
  byGroup.set("Other", other);
  manifest.groups.push({ name: "Other", description: "Skills that do not fit a group yet.", start: other[0].slug });
}

const groups = manifest.groups
  .filter((g) => byGroup.get(g.name)?.length > 0)
  .map((g) => ({ ...g, skills: byGroup.get(g.name) }));

const data = {
  repo: manifest.repo,
  siteUrl: manifest.siteUrl,
  generatedAt: new Date().toISOString(),
  groups,
  skillCount: skills.length,
  changelog: manifest.changelog,
};

const out = `// Generated by scripts/build-site-data.mjs from skills/ and scripts/site-manifest.json. Do not edit.\nwindow.AI_SKILLS = ${JSON.stringify(data, null, 2)};\n`;
writeFileSync(join(root, "docs/skills-data.js"), out);
console.log(`wrote docs/skills-data.js (${skills.length} skills, ${groups.length} groups)`);
